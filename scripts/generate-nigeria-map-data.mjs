// One-off preprocessing script (not part of the app build) that converts the
// vendored geoBoundaries Nigeria ADM1 geojson into compact, pre-projected SVG
// path strings so the app never parses/ships the raw ~800KB geojson at
// runtime. Re-run with `node scripts/generate-nigeria-map-data.mjs` only if
// data/brucellosis/nigeria-states.geojson is ever replaced.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const geojsonPath = path.join(root, "data/brucellosis/nigeria-states.geojson");
const outPath = path.join(root, "data/brucellosis/nigeria-states-paths.ts");

const VIEW_WIDTH = 700;
const RDP_EPSILON_PX = 0.6;

const gj = JSON.parse(readFileSync(geojsonPath, "utf8"));

let minLon = Infinity;
let maxLon = -Infinity;
let minLat = Infinity;
let maxLat = -Infinity;
for (const f of gj.features) {
  for (const ring of f.geometry.coordinates) {
    for (const [lon, lat] of ring) {
      if (lon < minLon) minLon = lon;
      if (lon > maxLon) maxLon = lon;
      if (lat < minLat) minLat = lat;
      if (lat > maxLat) maxLat = lat;
    }
  }
}
const lonRange = maxLon - minLon;
const latRange = maxLat - minLat;
const VIEW_HEIGHT = Math.round((VIEW_WIDTH / lonRange) * latRange);

function project([lon, lat]) {
  const x = ((lon - minLon) / lonRange) * VIEW_WIDTH;
  const y = ((maxLat - lat) / latRange) * VIEW_HEIGHT;
  return [Number(x.toFixed(1)), Number(y.toFixed(1))];
}

// Ramer-Douglas-Peucker simplification on projected [x,y] points.
function rdp(points, epsilon) {
  if (points.length < 3) return points;
  let maxDist = -1;
  let maxIndex = 0;
  const [x1, y1] = points[0];
  const [x2, y2] = points[points.length - 1];
  const dx = x2 - x1;
  const dy = y2 - y1;
  const norm = Math.sqrt(dx * dx + dy * dy) || 1;
  for (let i = 1; i < points.length - 1; i++) {
    const [px, py] = points[i];
    const dist = Math.abs(dy * px - dx * py + x2 * y1 - y2 * x1) / norm;
    if (dist > maxDist) {
      maxDist = dist;
      maxIndex = i;
    }
  }
  if (maxDist > epsilon) {
    const left = rdp(points.slice(0, maxIndex + 1), epsilon);
    const right = rdp(points.slice(maxIndex), epsilon);
    return [...left.slice(0, -1), ...right];
  }
  return [points[0], points[points.length - 1]];
}

// GeoJSON rings are closed (first point === last point), which breaks plain
// RDP: the first/last reference "line" is a single point, so every
// perpendicular distance evaluates to 0 and the whole ring collapses. Split
// the closed ring in two at the point farthest from the start, simplify each
// open half independently, then stitch back into a closed ring.
function simplifyClosedRing(points, epsilon) {
  const open = points[0][0] === points[points.length - 1][0] && points[0][1] === points[points.length - 1][1]
    ? points.slice(0, -1)
    : points;
  if (open.length < 4) return open;

  let farIndex = 1;
  let farDist = -1;
  const [x0, y0] = open[0];
  for (let i = 1; i < open.length; i++) {
    const [px, py] = open[i];
    const d = (px - x0) ** 2 + (py - y0) ** 2;
    if (d > farDist) {
      farDist = d;
      farIndex = i;
    }
  }

  const firstHalf = rdp(open.slice(0, farIndex + 1), epsilon);
  const secondHalf = rdp([...open.slice(farIndex), open[0]], epsilon);
  return [...firstHalf.slice(0, -1), ...secondHalf.slice(0, -1)];
}

function ringToPath(ring) {
  const projected = ring.map(project);
  const simplified = simplifyClosedRing(projected, RDP_EPSILON_PX);
  const [first, ...rest] = simplified;
  return `M${first[0]},${first[1]}${rest.map(([x, y]) => `L${x},${y}`).join("")}Z`;
}

const states = gj.features
  .map((f) => {
    const name = f.properties.shapeName;
    const d = f.geometry.coordinates.map(ringToPath).join(" ");
    // Centroid of the largest ring, for optional label placement.
    const largestRing = f.geometry.coordinates.reduce((a, b) => (a.length > b.length ? a : b));
    const projectedRing = largestRing.map(project);
    const cx = projectedRing.reduce((sum, [x]) => sum + x, 0) / projectedRing.length;
    const cy = projectedRing.reduce((sum, [, y]) => sum + y, 0) / projectedRing.length;
    return { name, d, cx: Number(cx.toFixed(1)), cy: Number(cy.toFixed(1)) };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const header = `// Generated by scripts/generate-nigeria-map-data.mjs — do not hand-edit.
// Source: geoBoundaries.org Nigeria ADM1 (CC BY 4.0), simplified release
// geoBoundaries-NGA-ADM1_simplified.geojson, boundary year 2022.
// Attribution: Runfola, D. et al. (2020) geoBoundaries: A global database of
// political administrative boundaries. PLoS ONE 15(4).
export interface NigeriaStatePath {
  name: string;
  d: string;
  cx: number;
  cy: number;
}

export const NIGERIA_MAP_VIEWBOX = "0 0 ${VIEW_WIDTH} ${VIEW_HEIGHT}" as const;

export const nigeriaStatePaths: NigeriaStatePath[] = ${JSON.stringify(states, null, 2)};
`;

writeFileSync(outPath, header);

const totalPointsBefore = gj.features.reduce(
  (sum, f) => sum + f.geometry.coordinates.reduce((s, r) => s + r.length, 0),
  0,
);
const totalPointsAfter = states.reduce((sum, s) => sum + (s.d.match(/[LM]/g)?.length ?? 0), 0);
console.log(`States: ${states.length}`);
console.log(`Points before simplification: ${totalPointsBefore}`);
console.log(`Points after simplification: ${totalPointsAfter}`);
console.log(`ViewBox: 0 0 ${VIEW_WIDTH} ${VIEW_HEIGHT}`);
console.log(`Wrote ${outPath}`);

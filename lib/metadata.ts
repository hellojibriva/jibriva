import type { Metadata } from "next";
import { siteConfig } from "@/config/site";

interface PageMetadataInput {
  /** Page name, e.g. "About". Omit on the homepage to use the full site title. */
  title?: string;
  description: string;
  path: string;
  ogType?: "website" | "profile";
  noIndex?: boolean;
}

export const defaultTitle = `${siteConfig.name} | ${siteConfig.title}`;

/** Builds a per-route Metadata object: "{Page} · Abi Precious Jibrin", canonical, OG and Twitter Card. */
export function buildMetadata({
  title,
  description,
  path,
  ogType = "website",
  noIndex = false,
}: PageMetadataInput): Metadata {
  const fullTitle = title ? `${title} · ${siteConfig.name}` : defaultTitle;
  const url = `${siteConfig.domain}${path}`;
  // A page-level openGraph object replaces the root one, so the shared image
  // generated by app/opengraph-image.tsx is referenced explicitly here.
  const image = {
    url: "/opengraph-image",
    width: 1200,
    height: 630,
    alt: `${siteConfig.name}, ${siteConfig.title}`,
  };

  return {
    title: { absolute: fullTitle },
    description,
    alternates: { canonical: url },
    robots: noIndex ? { index: false, follow: true } : { index: true, follow: true },
    openGraph: {
      title: fullTitle,
      description,
      url,
      siteName: siteConfig.name,
      type: ogType,
      locale: "en_GB",
      images: [image],
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      images: [image.url],
    },
  };
}
